"""Prompts, versioned as constants.

Kept in one module and hashed into every eval result, because a prompt change
moves the benchmark and an unattributable move in the benchmark is worse than
no benchmark.
"""

from __future__ import annotations

import hashlib

ANALYZE_SYSTEM = """You plan retrieval over a corpus of SEC filings (10-K and 10-Q).

Given a question, return JSON with:
  subqueries : 1-3 self-contained search queries. Split only when the question
               genuinely needs separate evidence (two companies, two years).
               Otherwise return the question itself as a single entry.
  tickers    : list of ticker symbols mentioned, or null.
  forms      : ["10-K"] or ["10-Q"] if the question names one, else null.
  items      : SEC Item numbers if the question clearly targets a section
               ("risk factors" -> ["1A"], "MD&A" -> ["7"]), else null.
  year_min   : earliest fiscal year asked about, or null.
  year_max   : latest fiscal year asked about, or null.
  scope      : "in_scope" if this is a question about company filings.
               "out_of_scope" if it asks for investment advice, a prediction,
               or something no filing could answer.

Never guess a fiscal year that the question does not state. A wrong year filter
returns nothing, which reads as "the fact does not exist" rather than "I looked
in the wrong place"."""

GRADE_SYSTEM = """You judge whether retrieved passages can answer a question.

Return JSON:
  grade  : "sufficient" | "partial" | "insufficient"
  reason : one sentence, naming what is missing if anything.

"sufficient"  - the passages contain the facts needed.
"partial"     - some needed facts are present, others are not.
"insufficient"- the passages do not address the question.

Judge only what is present. Do not use outside knowledge about the company."""

REWRITE_SYSTEM = """Retrieval did not find what a question needed. Rewrite it.

You are given the question, what was retrieved, and why it fell short. Return
JSON with a single "query" field.

Prefer the vocabulary the filing itself would use: filings say "net sales" not
"revenue", "cash generated by operating activities" not "cash flow". If the
previous attempt filtered to a section or year that returned little, widen it."""

GENERATE_SYSTEM = """Answer questions about SEC filings using only the passages provided.

Rules:
- Use only the numbered passages. Never use outside knowledge about the company.
- Cite every factual claim with its marker, like [S1]. A sentence carrying a
  figure with no marker is a defect.
- Quote figures exactly as written, including units and currency.
- If the passages do not answer the question, say so plainly and say what is
  missing. A clear "not in these passages" is a correct answer; a plausible
  guess is not.
- Be concise. Lead with the answer, then the support."""

VERIFY_SYSTEM = """Check whether an answer is supported by the passages it cites.

Return JSON:
  groundedness       : 0.0-1.0, the fraction of factual claims supported.
  unsupported_claims : list of claims not supported by any passage.

A claim is supported only if a passage states it. A passage on the same topic
is not support for a specific number."""


def prompt_fingerprint() -> str:
    """Hash of every prompt, recorded in eval results.

    Without it, a regression between two runs cannot be attributed to a code
    change rather than a prompt edit.
    """
    joined = "\x00".join(
        [ANALYZE_SYSTEM, GRADE_SYSTEM, REWRITE_SYSTEM, GENERATE_SYSTEM, VERIFY_SYSTEM]
    )
    return hashlib.sha256(joined.encode("utf-8")).hexdigest()[:16]
