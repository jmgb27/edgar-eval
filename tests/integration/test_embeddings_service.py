"""The embeddings service, against the real container.

Marked `integration` because it needs the service up. The unit suite must stay
runnable with nothing but a Python interpreter, so nothing here is imported by
tests/unit.

These assertions are deliberately about *semantics*, not shape. A service that
returns 1024 well-formed floats per call but ranks unrelated text above the
answer would pass a shape test and destroy every downstream metric.
"""

from __future__ import annotations

import math

import httpx
import pytest

from edgar_eval.config import settings
from edgar_eval.embed.client import EmbeddingsClient

pytestmark = pytest.mark.integration


@pytest.fixture(scope="module")
def client() -> EmbeddingsClient:
    c = EmbeddingsClient()
    try:
        c.health()
    except (httpx.TransportError, httpx.HTTPStatusError) as exc:
        pytest.skip(f"embeddings service unavailable at {settings.embeddings_url}: {exc}")
    return c


def _cosine(a: list[float], b: list[float]) -> float:
    return sum(x * y for x, y in zip(a, b, strict=True))


def test_health_reports_the_configured_models(client: EmbeddingsClient) -> None:
    health = client.health()
    assert health["status"] == "ok"
    assert health["embedding_model"] == settings.embedding_model
    assert health["reranker_model"] == settings.reranker_model
    assert health["dim"] == settings.embedding_dim


def test_embedding_width_matches_the_schema(client: EmbeddingsClient) -> None:
    """A mismatch here means every insert would fail deep inside an ingest."""
    vec = client.embed_one("Net cash provided by operating activities.")
    assert len(vec) == settings.embedding_dim


def test_embeddings_are_unit_normalised(client: EmbeddingsClient) -> None:
    """The hybrid query treats cosine distance as a dot product, and the
    halfvec index assumes unit vectors. Un-normalised output would skew every
    ranking without erroring anywhere."""
    for vec in client.embed(["short text", "a considerably longer passage " * 40]):
        assert math.isclose(math.sqrt(sum(x * x for x in vec)), 1.0, abs_tol=1e-3)


def test_semantically_related_text_is_closer_than_unrelated(client: EmbeddingsClient) -> None:
    query, related, unrelated = client.embed(
        [
            "How much cash did the company generate from operations?",
            "Net cash generated by operating activities was $110.5 billion.",
            "The Board declared a quarterly dividend on common stock.",
        ]
    )
    assert _cosine(query, related) > _cosine(query, unrelated)


def test_long_input_is_not_truncated_into_meaninglessness(client: EmbeddingsClient) -> None:
    """bge-m3 was chosen over bge-large-en-v1.5 precisely for its 8192-token
    window: a preserved 10-K table blows straight past 512 tokens. If the
    service silently truncated, a distinctive fact late in a long chunk would
    become unretrievable -- so assert that it is still found."""
    filler = "This paragraph discusses general corporate matters. " * 200
    needle = "The effective tax rate for fiscal 2023 was 14.7 percent."

    long_chunk, query = client.embed([filler + needle, "What was the effective tax rate?"])
    filler_only = client.embed_one(filler)

    assert _cosine(query, long_chunk) > _cosine(query, filler_only)


def test_reranker_puts_the_answer_first(client: EmbeddingsClient) -> None:
    """The Phase 1 exit criterion: a hand-made set where the correct document
    is deliberately last must come back first."""
    documents = [
        "The Board declared a quarterly cash dividend of $0.24 per share.",
        "Our properties consist of manufacturing facilities and office space.",
        "Item 4. Mine Safety Disclosures. Not applicable.",
        "Net cash provided by operating activities was $110,543 million in 2023.",
    ]
    hits = client.rerank("What was net cash provided by operating activities?", documents)

    assert len(hits) == len(documents)
    assert hits[0].index == 3, "the answering passage did not rank first"
    assert hits[0].score > hits[-1].score


def test_reranker_scores_are_comparable_across_queries(client: EmbeddingsClient) -> None:
    """Scores must be sigmoid-normalised to 0..1, or the fixed
    RERANK_MIN_SCORE threshold means something different per query."""
    hits = client.rerank(
        "effective tax rate", ["The effective tax rate was 14.7%.", "Mine safety."]
    )
    assert all(0.0 <= h.score <= 1.0 for h in hits)
    assert hits[0].score > settings.rerank_min_score
    assert hits[-1].score < hits[0].score


def test_top_k_limits_the_result_set(client: EmbeddingsClient) -> None:
    hits = client.rerank("revenue", ["a", "b", "c", "d"], top_k=2)
    assert len(hits) == 2


def test_empty_input_is_handled_without_a_round_trip(client: EmbeddingsClient) -> None:
    assert client.embed([]) == []
    assert client.rerank("q", []) == []
