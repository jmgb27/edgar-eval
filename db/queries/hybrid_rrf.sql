-- Hybrid retrieval: dense (HNSW) + lexical (GIN), fused by Reciprocal Rank
-- Fusion, filtered on metadata.
--
-- Why RRF rather than a weighted sum of scores: the two arms produce scores on
-- incomparable scales. Cosine distance is bounded and calibrated; Postgres
-- `ts_rank_cd` is an un-normalised term-frequency rank with no IDF and no
-- length normalisation -- it is *not* BM25, and calling it that would be
-- wrong. RRF only reads each arm's *rank*, so the lexical arm's uncalibrated
-- magnitudes cannot skew the fusion. k=60 is the constant from Cormack et al.
-- (2009); it is not a tuning knob to fiddle with casually.
--
-- `in_dense` / `in_lexical` are returned deliberately. They flow into the
-- Langfuse retriever span and into the UI as provenance badges, so a reviewer
-- can see the hybrid earning its keep: ticker and figure queries surface
-- lexical-only hits, paraphrased questions surface dense-only ones.
--
-- Every filter is a "NULL means unfiltered" parameter so one query serves both
-- the filtered and the unfiltered path; the planner drops the OR branch when
-- the parameter is non-null.

WITH params AS (
    SELECT
        %(qvec)s::halfvec(1024) AS qvec,
        %(qtext)s::text         AS qtext,
        %(tickers)s::text[]     AS f_tickers,
        %(forms)s::text[]       AS f_forms,
        %(items)s::text[]       AS f_items,
        %(year_min)s::int       AS f_year_min,
        %(year_max)s::int       AS f_year_max,
        %(pool)s::int           AS n_pool,
        %(fused)s::int          AS n_out,
        %(rrf_k)s::int          AS rrf_k
),
filtered AS (
    SELECT c.*
    FROM chunks c, params p
    WHERE (p.f_tickers  IS NULL OR c.ticker      = ANY(p.f_tickers))
      AND (p.f_forms    IS NULL OR c.form_type   = ANY(p.f_forms))
      AND (p.f_items    IS NULL OR c.item        = ANY(p.f_items))
      AND (p.f_year_min IS NULL OR c.fiscal_year >= p.f_year_min)
      AND (p.f_year_max IS NULL OR c.fiscal_year <= p.f_year_max)
),
dense AS (
    SELECT f.id,
           ROW_NUMBER() OVER (ORDER BY f.embedding::halfvec(1024) <=> p.qvec) AS rank
    FROM filtered f, params p
    ORDER BY f.embedding::halfvec(1024) <=> p.qvec
    LIMIT (SELECT n_pool FROM params)
),
-- The lexical arm ORs its terms. This is not a detail.
--
-- `websearch_to_tsquery` AND-joins every lexeme, so the question "What was net
-- cash provided by operating activities?" becomes
--     'net' & 'cash' & 'provid' & 'oper' & 'activ'
-- which matched *zero* chunks of a real Apple 10-K -- because Apple writes
-- "Cash generated by operating activities". One synonym away from the filing's
-- wording and the entire arm returns nothing, silently reducing "hybrid
-- retrieval" to dense-only and making the hybrid row of the benchmark a lie.
--
-- Rewriting the parsed query's `&` operators to `|` keeps everything
-- websearch_to_tsquery is actually good at -- stemming, stop words, sanitising
-- untrusted input, and `<->` phrase operators from quoted strings, which are
-- deliberately left intact -- while making the arm recall-oriented. Precision
-- is not this arm's job: ts_rank_cd orders the matches, RRF reads only their
-- rank, and the cross-encoder makes the final call.
lexical AS (
    SELECT f.id,
           ROW_NUMBER() OVER (ORDER BY ts_rank_cd(f.tsv, q.query) DESC) AS rank
    FROM filtered f, params p,
         LATERAL (
             SELECT replace(websearch_to_tsquery('english', p.qtext)::text, '&', '|')::tsquery
         ) AS q(query)
    WHERE q.query IS NOT NULL
      AND f.tsv @@ q.query
    ORDER BY ts_rank_cd(f.tsv, q.query) DESC
    LIMIT (SELECT n_pool FROM params)
),
fused AS (
    SELECT id,
           SUM(w)                                            AS rrf_score,
           bool_or(src = 'dense')                            AS in_dense,
           bool_or(src = 'lexical')                          AS in_lexical
    FROM (
        SELECT id, 'dense'   AS src, 1.0 / ((SELECT rrf_k FROM params) + rank) AS w FROM dense
        UNION ALL
        SELECT id, 'lexical' AS src, 1.0 / ((SELECT rrf_k FROM params) + rank) AS w FROM lexical
    ) arms
    GROUP BY id
)
SELECT c.id, c.text, c.embed_text, c.table_html, c.has_table,
       c.ticker, c.form_type, c.fiscal_year, c.fiscal_period,
       c.item, c.item_title, c.section_path, c.source_url, c.page_number,
       c.accession_no,
       fu.rrf_score, fu.in_dense, fu.in_lexical
FROM fused fu
JOIN chunks c ON c.id = fu.id
ORDER BY fu.rrf_score DESC
LIMIT (SELECT n_out FROM params);
