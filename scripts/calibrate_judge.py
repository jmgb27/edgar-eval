"""Measure the faithfulness judge against known labels.

Runs the judge over `eval/labels/judge_calibration.jsonl` and reports its
confusion matrix, TPR and TNR. Writes `eval/judge_calibration_report.md`, which
is committed, so the number in the README is a claim someone can check rather
than a claim someone has to accept.

The gate is TPR > 0.90 and TNR > 0.90. Below either, the judge is not fit to
score anything: a judge with poor TPR waves hallucinations through, and one with
poor TNR floods the report with false alarms until people stop reading it.

Positive class is UNGROUNDED, so TPR reads as "of the answers we deliberately
corrupted, how many did it catch".
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from typing import Any

from edgar_eval.config import REPO_ROOT, settings
from edgar_eval.eval.judge import (
    ConfusionMatrix,
    judge_faithfulness,
    judge_prompt_sha256,
)
from edgar_eval.llm import build_judge
from edgar_eval.logging import configure_logging, get_logger

log = get_logger(__name__)

LABELS = REPO_ROOT / "eval" / "labels" / "judge_calibration.jsonl"
REPORT = REPO_ROOT / "eval" / "judge_calibration_report.md"

TPR_GATE = 0.90
TNR_GATE = 0.90


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--limit", type=int, help="score only the first N triples")
    args = parser.parse_args()

    configure_logging()
    if not settings.judge_configured:
        raise SystemExit("ANTHROPIC_API_KEY is not set; the judge cannot be calibrated without it.")

    triples = [json.loads(line) for line in LABELS.read_text().splitlines() if line.strip()]
    if args.limit:
        triples = triples[: args.limit]

    llm = build_judge(max_tokens=800)
    try:
        # One cheap probe before the loop. Without it a billing or auth
        # failure surfaces as a raw traceback partway through the set,
        # after the run has already spent money on the triples before it.
        judge_faithfulness(question="ping", answer="1", contexts=["1"], llm=llm)
    except Exception as exc:
        detail = str(exc)
        if "credit balance is too low" in detail:
            raise SystemExit(
                "The Anthropic key authenticates but the account has no credits, so the\n"
                "judge cannot run. Nothing else in this repository needs it:\n"
                "  make eval-retrieval   recall, nDCG, MRR and citation accuracy, free\n"
                "  make gate             the CI quality gate, free\n"
                "Set JUDGE_MODEL and ANTHROPIC_API_KEY to another provider, or top up."
            ) from exc
        raise SystemExit(f"judge unavailable: {detail}") from exc

    matrix = ConfusionMatrix()
    disagreements: list[dict[str, Any]] = []
    started = time.monotonic()

    for i, triple in enumerate(triples, start=1):
        truth_ungrounded = triple["label"] == "UNGROUNDED"
        verdict = judge_faithfulness(
            question=triple["question"],
            answer=triple["answer"],
            contexts=triple["contexts"],
            llm=llm,
        )
        matrix.add(truth_ungrounded=truth_ungrounded, judged_ungrounded=not verdict.supported)

        agreed = truth_ungrounded == (not verdict.supported)
        if not agreed:
            disagreements.append(
                {
                    "id": triple["id"],
                    "truth": triple["label"],
                    "judged": verdict.label,
                    "question": triple["question"],
                    "answer": triple["answer"],
                    "why": triple["why"],
                    "judge_reason": verdict.reason,
                }
            )
        log.info("calibrate", i=i, n=len(triples), id=triple["id"], agreed=agreed)

    elapsed = time.monotonic() - started
    stats = matrix.as_dict()
    passed = (
        stats["tpr"] is not None
        and stats["tnr"] is not None
        and stats["tpr"] > TPR_GATE
        and stats["tnr"] > TNR_GATE
    )

    def fmt(value: float | None) -> str:
        return "—" if value is None else f"{value:.3f}"

    lines = [
        "# Judge calibration",
        "",
        "Every faithfulness number this repository publishes comes from an LLM judge.",
        "An uncalibrated judge produces figures that look like evidence without being",
        "evidence, so the judge is measured against known labels before it is allowed",
        "to score anything. This file is generated by `scripts/calibrate_judge.py`.",
        "",
        f"- **Judge**: `{settings.judge_model}`, temperature 0",
        f"- **Prompt**: `{judge_prompt_sha256()}` (see `src/edgar_eval/eval/judge.py`)",
        f"- **Set**: `{LABELS.relative_to(REPO_ROOT)}`, {stats['n']} triples, balanced 50/50",
        f"- **Runtime**: {elapsed:.0f}s",
        "",
        "## How the labels are known",
        "",
        "Each triple is a matched pair built from the curated gold set: the verified",
        "reference answer with its supporting passage (GROUNDED), and the same answer",
        "with exactly one fact corrupted against the same passage (UNGROUNDED). The",
        "label is therefore certain by construction rather than by anyone's judgement,",
        "and the pair isolates the thing that matters — noticing that a figure changed.",
        "",
        "## Results",
        "",
        "Positive class is UNGROUNDED: TPR is the share of deliberately corrupted",
        "answers the judge caught; TNR is the share of sound answers it left alone.",
        "",
        "| Metric | Value | Gate |",
        "|---|---|---|",
        f"| TPR (hallucinations caught) | **{fmt(stats['tpr'])}** | > {TPR_GATE:.2f} |",
        f"| TNR (sound answers left alone) | **{fmt(stats['tnr'])}** | > {TNR_GATE:.2f} |",
        f"| Precision | {fmt(stats['precision'])} | — |",
        f"| F1 | {fmt(stats['f1'])} | — |",
        f"| Accuracy | {fmt(stats['accuracy'])} | — |",
        "",
        "| | judged UNGROUNDED | judged GROUNDED |",
        "|---|---|---|",
        f"| **truly UNGROUNDED** | {stats['tp']} (TP) | {stats['fn']} (FN — missed) |",
        f"| **truly GROUNDED** | {stats['fp']} (FP — false alarm) | {stats['tn']} (TN) |",
        "",
        f"**Verdict: {'fit to score' if passed else 'NOT fit to score'}.**",
        "",
    ]

    if disagreements:
        lines += [
            f"## Disagreements ({len(disagreements)})",
            "",
            "Listed in full rather than summarised: the cases a judge gets wrong are",
            "the ones that tell you what its scores mean.",
            "",
        ]
        for d in disagreements:
            lines += [
                f"### `{d['id']}` — truth {d['truth']}, judged {d['judged']}",
                "",
                f"- **Question**: {d['question']}",
                f"- **Answer**: {d['answer']}",
                f"- **Label rationale**: {d['why']}",
                f"- **Judge said**: {d['judge_reason']}",
                "",
            ]
    else:
        lines += ["## Disagreements", "", "None — the judge agreed with every label.", ""]

    report = "\n".join(lines)
    REPORT.write_text(report)

    print(report[: report.index("## How the labels")])
    print(f"  TPR {fmt(stats['tpr'])}   TNR {fmt(stats['tnr'])}   F1 {fmt(stats['f1'])}")
    print(f"  {len(disagreements)} disagreement(s)")
    print(f"  → {REPORT.relative_to(REPO_ROOT)}")
    return 0 if passed else 1


if __name__ == "__main__":
    sys.exit(main())
